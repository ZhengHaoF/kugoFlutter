#!/usr/bin/env python3
"""Generate the approved G branding assets. Requires Pillow (developer only)."""
import argparse
import io
from pathlib import Path
import struct

from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
BACKGROUND = "#F2F4F8"
ICO_SIZES = (16, 20, 24, 32, 40, 48, 64, 128, 256)


def png_bytes(image):
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


def ico_bytes(mark):
    """Embed independently rendered PNG frames, including native tray sizes."""
    frames = [png_bytes(render(mark, size, 0.86)) for size in ICO_SIZES]
    result = bytearray(struct.pack("<HHH", 0, 1, len(frames)))
    offset = 6 + 16 * len(frames)
    for size, frame in zip(ICO_SIZES, frames):
        result.extend(
            struct.pack(
                "<BBBBHHII", size % 256, size % 256, 0, 0, 1, 32, len(frame), offset
            )
        )
        offset += len(frame)
    for frame in frames:
        result.extend(frame)
    return bytes(result)


def render(mark, size, fraction, background=None, monochrome=False):
    image = Image.new("RGBA", (size, size), background or (0, 0, 0, 0))
    symbol = mark.copy()
    box = round(size * fraction)
    symbol.thumbnail((box, box), Image.Resampling.LANCZOS)
    if monochrome:
        solid = Image.new("RGBA", symbol.size, (0, 0, 0, 255))
        solid.putalpha(symbol.getchannel("A"))
        symbol = solid
    image.alpha_composite(symbol, ((size - symbol.width) // 2, (size - symbol.height) // 2))
    return image


def outputs():
    source = Image.open(ROOT / "branding/icon-g-source.png").convert("RGBA")
    bbox = source.getchannel("A").point(lambda a: 255 if a > 32 else 0).getbbox()
    if bbox is None:
        raise ValueError("Brand source is empty")
    mark = source.crop(bbox)
    files = {"branding/icon-g-master.png": png_bytes(render(mark, 1024, 0.86))}
    for density, size in (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96), ("xxhdpi", 144), ("xxxhdpi", 192)):
        files[f"android/app/src/main/res/mipmap-{density}/ic_launcher.png"] = png_bytes(
            render(mark, size, 0.72, BACKGROUND)
        )
    # Fit the asymmetric tail inside the central 66dp safe CIRCLE, not just
    # its bounding square. 50dp artwork on a 108dp canvas leaves radial margin.
    files["android/app/src/main/res/drawable-nodpi/ic_launcher_foreground.png"] = png_bytes(
        render(mark, 432, 50 / 108)
    )
    files["android/app/src/main/res/drawable-nodpi/ic_launcher_monochrome.png"] = png_bytes(
        render(mark, 432, 50 / 108, monochrome=True)
    )
    files["windows/runner/resources/app_icon.ico"] = ico_bytes(mark)
    files["assets/app_icon.ico"] = ico_bytes(mark)
    files["assets/app_icon.png"] = png_bytes(render(mark, 256, 0.86))
    files["assets/tray_icon.ico"] = ico_bytes(mark)
    files["assets/tray_icon.png"] = png_bytes(render(mark, 64, 0.86))
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Compare generated bytes with committed assets")
    args = parser.parse_args()
    bad = []
    for relative, data in outputs().items():
        path = ROOT / relative
        if args.check:
            if not path.is_file() or path.read_bytes() != data:
                bad.append(relative)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        print(f"{'CHECK' if args.check else 'WRITE'} {relative}")
    if bad:
        raise SystemExit("Stale or missing icons: " + ", ".join(bad))


if __name__ == "__main__":
    main()
